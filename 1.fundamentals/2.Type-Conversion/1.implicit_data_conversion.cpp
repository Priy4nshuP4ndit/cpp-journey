#include <iostream>
using namespace std;
int main(){
    // Done automatically by compiler


    // Example 1 (int to double)
    int i = 20;
    double j = i;
    cout << "int i = " << i<<endl;
    cout << "double j = i: " << j<<endl;


    //Example 2 (char to int ----> ASCSII value)
    int a = 'a';
    int b = 'b';
    int $ = '$';
    cout<< "ASCII value of a: " << a <<endl;
    cout << "ASCII value of b: " << b<<endl;
    cout << "ASCII value of $: " << $ <<endl;

    //Example 3 (int + double)
    int x = 90;
    double y = 5.5;
    cout << "90 + 5.5 = " << x+y << endl;



    return 0;
}