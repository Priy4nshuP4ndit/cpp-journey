#include <iostream>
using namespace std;
int main(){

    // == equals to
    // != not equals to
    // < less than
    // <= less than or equals to
    // > greater than
    // >= greater than equals to

    int x = 10 , y = 20 , z= 10;
    cout<<"is 10 = 10: " << (x==z) << endl;
    cout<<"is 10 != 10: " << (x!=z) << endl;
    cout<<"is 10 < 20: " << (x<y) << endl;
    cout<<"is 10 <= 20: " << (x<=y) << endl;
     cout<<"is 10 >= 20: " << (x>=y) << endl;

    return 0;
}
    
    

